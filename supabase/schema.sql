-- current:
--
--   supabase/SECURITY.md   the access model — what each role can reach, the
--                          three barriers against role escalation, and why the
--                          helper functions are SECURITY DEFINER
--   supabase/OAUTH.md      Google and Apple sign-in
--
-- The tests that hold the access model to its word are in supabase/tests/ and
