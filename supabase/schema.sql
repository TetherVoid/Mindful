-- This file used to be a single idempotent script pasted into the SQL Editor by
-- hand. That was workable while the database was empty. It stopped being
-- workable the moment production had real users in it, for one reason: a script
-- that describes the intended end state cannot describe how to GET there from
-- whatever a particular database currently holds. `create table if not exists`
-- does nothing at all to a table whose columns are wrong, and nothing records
-- which parts of the script a given database has already seen.
--
-- Migrations answer both. Each file runs once, in order, against a database
-- whose history is recorded, and `supabase db reset` replays the sequence from
-- empty — so the upgrade is exercised before it reaches anybody's data.
--
-- The previous contents of this file are not lost; they are the source the
-- migrations were split out of, and `git show HEAD:supabase/schema.sql` still
-- has them.
--
